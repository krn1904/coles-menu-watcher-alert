export function getBrandKeyFromNormalized(normalizedName, significantTokens) {
  for (const brand of MULTI_WORD_BRANDS) {
    if (normalizedName.includes(brand)) return brand.replace(/\s+/g, " ").trim();
  }
  for (const token of significantTokens) {
    if (SINGLE_TOKEN_BRANDS.has(token)) return token;
  }
  return significantTokens[0] || "";
}
